const $=s=>document.querySelector(s),checks=[];
const wait=async fn=>{for(let i=0;i<160;i++){if(await fn())return;await new Promise(r=>setTimeout(r,60));}throw Error('等待界面超时');};
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const assert=(ok,message)=>{if(!ok)throw Error(message);checks.push(message);};
const page=id=>{ $('[data-category="arm-config"]').click();$(`.function-menu [data-function-page="${id}"]`).click();};
const field=(id,path)=>$(`[data-config-page="${id}"] [data-arm-path="${path}"]`);
const change=(id,path,value)=>{const f=field(id,path);if(f.type==='checkbox')f.checked=value;else f.value=value;f.dispatchEvent(new Event('input',{bubbles:true}));};
const button=(id,action)=>$(`[data-config-page="${id}"] [data-hardware-action="${action}"]`);
const title=()=>$('[data-hardware-title]').textContent;
const fixture=async mode=>(await fetch('/hardware-fixture'+(mode?'?'+mode:''))).json();
const detect=async()=>{button('arm-connection','detect').click();await wait(()=>!button('arm-connection','detect').disabled);};
const save=async id=>{$(`[data-config-page="${id}"] [data-arm-action="save"]`).click();await wait(()=>$(`[data-config-page="${id}"] .arm-save-state`).textContent.includes('配置已保存'));};
function finish(result){const pre=document.createElement('pre');pre.hidden=true;pre.id='test-result';pre.textContent=JSON.stringify(result);document.body.append(pre);}
try {
  await wait(()=>document.body.dataset.workbenchReady==='true' && $('#loading').hidden);
  const connection='arm-connection',devices='arm-devices',startup='arm-startup';
  if(!sessionStorage.getItem('hardware-reload')) {
    const before=(await (await fetch('/api/sim/state')).json()).command_count;
    page(connection);await wait(()=>$('[data-hardware-interfaces]').textContent.includes('1000000'));
    assert((await fixture()).count===0,'首次无保存配置时只读取接口，不自动探测');
    await detect();
    assert(title().includes('1 台响应正常'),'检测到单台 S1，缺少 B 不误报双臂');
    page(devices);
    assert($('[data-hardware-arm="0"]').textContent.includes('7 / 7'),'六关节与夹爪节点响应分别统计');
    change(devices,'arms.0.bitrate','500000');
    page(connection);assert(title().includes('配置已更改'),'修改参数后旧检测结果立即失效');
    await detect();assert(title().includes('0 台响应正常'),'速率不一致时不报告机械臂响应正常');
    assert($('[data-hardware-result]').textContent.includes('速率不一致'),'速率错误明确显示原因');
    page(devices);button(devices,'adopt').click();
    assert(field(devices,'arms.0.bitrate').value==='1000000','采用系统实际速率填入草稿');
    const count=(await fixture()).count;await save(devices);
    assert((await fixture()).count===count,'保存设备参数不会发送探测或运动命令');
    await fixture('dual');page(connection);change(connection,'connection.layout','dual');await detect();
    assert(title().includes('2 台响应正常'),'双臂按 A/B 接口分别检测');
    await fixture('down');button(connection,'refresh').click();await wait(()=>!button(connection,'refresh').disabled);
    assert(title().includes('接口状态已改变'),'接口关闭后旧的正常检测结果失效');
    await fixture('stale');await detect();
    assert(title().includes('历史检测'),'过期结果标为历史，不显示为持续在线');
    page(startup);
    button(startup,'detect').click();await wait(()=>!button(startup,'detect').disabled);
    assert($('[data-config-page="arm-startup"] [data-hardware-feedback-title]').textContent===title(),'初始化页检测结果在当前按钮下方显示，与连接页同步');
    assert($('[data-config-page="arm-startup"] [data-hardware-feedback-result]').textContent.includes('7/7'),'初始化页直接显示关节与夹爪响应数');
    button(startup,'preflight').click();
    assert($('[data-hardware-preflight]').textContent.includes('需要重新检测'),'复位参数检查拒绝使用过期连接结果');
    assert([...$('[data-config-page="arm-startup"]').querySelectorAll('.arm-operation-grid button:not([data-hardware-action])')].every(b=>b.disabled),'运动复位保持未接入');
    change(startup,'arms.0.resetSpeed','6');
    assert($('[data-hardware-preflight]').textContent.includes('参数已更改'),'修改复位参数会撤销旧参数检查');
    await fixture('failure');button(startup,'detect').click();await wait(()=>!button(startup,'detect').disabled);
    assert($('[data-config-page="arm-startup"] [data-hardware-feedback-result]').textContent.includes('超时'),'初始化页原地显示检测失败原因');
    page(connection);
    assert(title()==='检测未完成' && $('[data-hardware-result]').textContent.includes('超时'),'检测失败保留具体原因');
    await fixture('normal');change(connection,'connection.layout','single');await detect();
    assert(title().includes('1 台响应正常'),'失败后可以重试恢复');
    assert($('[data-arm-index="1"]').disabled,'单臂模式停用 B，保留其参数');
    page(startup);
    assert((await fixture()).motorCommands===0,'启动、检测、配置和自动流程没有发送任何使能或失能');
    assert(button(startup,'enable').disabled && !button(startup,'read').disabled && !button(startup,'disable').disabled,'读取和失能可用，使能等待新鲜状态和现场确认');
    const operate=async action=>{button(startup,action).click();await wait(()=>!button(startup,'read').disabled);};
    await operate('read');
    assert($('[data-hardware-state]').textContent.includes('已失能') && $('[data-hardware-state]').querySelectorAll('tbody tr').length===7,'读取实际关节与夹爪反馈，在当前页显示七个节点');
    assert((await fixture()).motorCommands===0,'读取状态不发送使能或失能');
    const confirmation=$('[data-hardware-confirm]');confirmation.checked=true;confirmation.dispatchEvent(new Event('change',{bubbles:true}));
    assert(!button(startup,'enable').disabled,'读取完整状态且勾选现场确认后可使能');
    await operate('enable');
    assert($('[data-hardware-operation-message]').textContent.includes('全部节点已确认使能'),'使能后读取反馈确认成功');
    assert(!confirmation.checked,'使能操作后清除确认，防止重复误触');
    await fixture('motor-refuse');await operate('disable');
    assert($('[data-hardware-operation-message]').textContent.includes('未完全确认'),'设备未执行失能时不误报成功');
    await fixture('normal');await operate('disable');
    assert($('[data-hardware-operation-message]').textContent.includes('全部节点已确认失能'),'失能无需先勾选使能确认，并核对真实反馈');
    await fixture('motor-partial');await operate('read');
    confirmation.checked=true;confirmation.dispatchEvent(new Event('change',{bubbles:true}));
    assert(button(startup,'enable').disabled && !button(startup,'disable').disabled,'有节点无反馈时阻止使能，仍允许尝试失能');
    await fixture('motor-fault');await operate('read');
    assert(button(startup,'enable').disabled && $('[data-hardware-state]').textContent.includes('过压'),'电机故障有明确提示并阻止使能');
    await fixture('motor-stale');await operate('read');
    assert(button(startup,'enable').disabled && $('[data-hardware-state]').textContent.includes('历史'),'旧状态不能用于使能');
    await fixture('normal');await operate('read');
    page(connection);
    await save(connection);
    assert((await (await fetch('/api/sim/state')).json()).command_count===before,'整个配置流程不改变仿真姿态或发送运动命令');
    sessionStorage.setItem('hardware-checks',JSON.stringify(checks));sessionStorage.setItem('hardware-reload',String((await fixture()).count));
    location.reload();
  } else {
    checks.push(...JSON.parse(sessionStorage.getItem('hardware-checks')));
    const prior=Number(sessionStorage.getItem('hardware-reload'));
    assert(field(devices,'arms.0.bitrate').value==='1000000','重新加载恢复已保存的实际速率');
    assert((await fixture()).count===prior,'启动软件后尚未打开配置页时不探测');
    page(connection);await wait(()=>title().includes('1 台响应正常'));
    assert((await fixture()).count===prior+1,'已有保存配置时打开页面自动检测一次');
    page(devices);page(connection);await pause(2200);
    assert((await fixture()).count===prior+1,'页面切换不重复自动探测');
    finish({ok:true,checks});
  }
} catch(error){finish({ok:false,checks,error:error.stack});}
